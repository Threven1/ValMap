// Builds js/icons.js from the game-icons.net SVG repository (CC BY 3.0).
//
//   1. Download https://github.com/game-icons/icons/archive/refs/heads/master.zip
//   2. Extract it somewhere
//   3. node tools/build-icons.js <path-to-extracted-icons-master>
//
// Only icons referenced in js/catalog.js are included. Each icon becomes a
// single SVG path string (512x512 box) so the app can draw it in any color.

const fs = require('fs');
const path = require('path');
const CATALOG = require('../js/catalog.js');

const src = process.argv[2];
if (!src) {
  console.error('Usage: node tools/build-icons.js <path-to-game-icons-repo>');
  process.exit(1);
}

const ids = new Set();
for (const b of CATALOG.biomes) ids.add(b.icon);
for (const p of CATALOG.common) ids.add(p.icon);
for (const list of Object.values(CATALOG.places)) for (const p of list) ids.add(p.icon);
for (const icon of Object.values(CATALOG.ui)) ids.add(icon);

const BACKGROUND = 'M0 0h512v512H0z';
const SAFE_PATH = /^[MmLlHhVvCcSsQqTtAaZz0-9.,\-\se]+$/;

const icons = {};
const authors = {};
for (const id of [...ids].sort()) {
  const file = path.join(src, ...id.split('/')) + '.svg';
  const svg = fs.readFileSync(file, 'utf8');
  const d = [...svg.matchAll(/<path\b[^>]*?\sd="([^"]+)"/g)]
    .map(m => m[1])
    .filter(p => p !== BACKGROUND)
    .join(' ');
  if (!d || !SAFE_PATH.test(d)) throw new Error(`Unexpected SVG content in ${id}`);
  icons[id] = d;
  const author = id.split('/')[0];
  (authors[author] = authors[author] || []).push(id.split('/')[1]);
}

const out = `// Generated by tools/build-icons.js. Do not edit by hand.
// Icons from https://game-icons.net, licensed CC BY 3.0. See CREDITS.md.
window.ICONS = ${JSON.stringify(icons, null, 0).replace(/","/g, '",\n"')};
`;
fs.writeFileSync(path.join(__dirname, '..', 'js', 'icons.js'), out);

console.log(`Wrote ${Object.keys(icons).length} icons to js/icons.js`);
for (const [a, list] of Object.entries(authors)) console.log(`  ${a}: ${list.join(', ')}`);
